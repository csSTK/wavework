#!/usr/bin/env bash
# Runs a child's new/changed tests against the pre-change code and classifies every test:
#   RED          failed on old code (good: the test proves something)
#   RED-COMPILE  old code does not compile / import against the test (accepted)
#   GREEN-ON-OLD passed on old code (suspicious: the test may prove nothing)
#   UNCHANGED    passed on old code, but the child did not touch this test (ignore)
#   SKIP <area>: unsupported   the area's test layout is not understood (see below); judge its tests from the diff
# Usage: red-green-check.sh <worktree> [<base-ref>]   (base-ref defaults to HEAD)
# Exit: 0 no GREEN-ON-OLD (or no changed tests), 1 any GREEN-ON-OLD, 2 tool/setup error.
# Writes only into a throwaway detached worktree in a temp dir (removed on exit). Tests in a changed file that
# were not themselves changed are classified too: judge those by the diff.
#
# Areas come from the checks of .claude/wavework.json (generated by `wavework init`/`update`, do not edit):
# one line 'name|kind|dir'. Understood kinds:
#   maven   *Test.java / *Tests.java / *IT.java under <dir>/src/test, run with ./mvnw (or mvn) test -Dtest=...
#   vitest  *.test.ts / *.test.tsx / *.test.js / *.test.jsx under <dir>, run with pnpm (pnpm-lock.yaml) or npm (package-lock.json)
# Any other area is `unsupported`: its tests are not run and the script prints SKIP.
# Needs bash, git and node. Testing seam: RED_GREEN_AREAS (same line format, one per line) replaces the table.
set -o pipefail

AREAS=(
  {{redGreenAreas}}
)
if [[ -n "${RED_GREEN_AREAS:-}" ]]; then
  AREAS=()
  while IFS= read -r line; do [[ -n "$line" ]] && AREAS+=("$line"); done <<< "$RED_GREEN_AREAS"
fi

die() { echo "red-green-check: $*" >&2; exit 2; }

[[ $# -ge 1 && $# -le 2 ]] || die "usage: $0 <worktree> [<base-ref>]"
WT="$(cd "$1" 2>/dev/null && pwd)" || die "worktree not found: $1"
BASE="${2:-HEAD}"
git -C "$WT" rev-parse --git-dir >/dev/null 2>&1 || die "not a git worktree: $WT"
git -C "$WT" rev-parse --verify --quiet "$BASE^{commit}" >/dev/null || die "unknown base ref: $BASE"
command -v node >/dev/null || die "node is required"

TMP="$(mktemp -d)" || die "cannot create temp dir"
OLD="$TMP/old"
cleanup() {
  git -C "$WT" worktree remove --force "$OLD" >/dev/null 2>&1 || true
  git -C "$WT" worktree prune >/dev/null 2>&1 || true
  rm -rf "$TMP"
}
trap cleanup EXIT

# Per area i: $TMP/test.i (changed test files), $TMP/support.i (changed helpers), $TMP/seen.i (any changed file).
AREA_NAME=() AREA_KIND=() AREA_DIR=()
for i in "${!AREAS[@]}"; do
  IFS="|" read -r "AREA_NAME[$i]" "AREA_KIND[$i]" "AREA_DIR[$i]" <<< "${AREAS[$i]}"
  : > "$TMP/test.$i"; : > "$TMP/support.$i"; : > "$TMP/seen.$i"
done

# Area of a path: the one with the longest matching dir ("." matches everything). Prints the index or nothing.
area_of() {
  local f="$1" best="" bestlen=-1 i d
  for i in "${!AREA_DIR[@]}"; do
    d="${AREA_DIR[$i]}"
    if [[ "$d" == "." ]]; then
      [[ 0 -gt $bestlen ]] && { best=$i; bestlen=0; }
    elif [[ "$f" == "$d"/* && ${#d} -gt $bestlen ]]; then
      best=$i; bestlen=${#d}
    fi
  done
  echo "$best"
}

# Changed files (added/copied/modified/renamed, tracked + untracked), NUL separated so names with spaces work.
while IFS= read -r -d '' f; do
  i="$(area_of "$f")"
  [[ -n "$i" ]] || continue
  rel="$f"; [[ "${AREA_DIR[$i]}" == "." ]] || rel="${f#"${AREA_DIR[$i]}"/}"
  echo "$f" >> "$TMP/seen.$i"
  case "${AREA_KIND[$i]}" in
    maven)
      case "$rel" in
        src/test/*.java) case "$rel" in *Test.java|*Tests.java|*IT.java) echo "$f" >> "$TMP/test.$i" ;; *) echo "$f" >> "$TMP/support.$i" ;; esac ;;
        src/test/*) echo "$f" >> "$TMP/support.$i" ;;
      esac ;;
    vitest)
      case "$rel" in
        *.test.ts|*.test.tsx|*.test.js|*.test.jsx) echo "$f" >> "$TMP/test.$i" ;;
        src/test/*) echo "$f" >> "$TMP/support.$i" ;;
      esac ;;
  esac
done < <(
  { git -C "$WT" diff --name-only -z --diff-filter=ACMR "$BASE" --; git -C "$WT" ls-files -z --others --exclude-standard; } | sort -zu
)

ANY=0
for i in "${!AREA_NAME[@]}"; do
  if [[ "${AREA_KIND[$i]}" != maven && "${AREA_KIND[$i]}" != vitest ]]; then
    [[ -s "$TMP/seen.$i" ]] && echo "SKIP ${AREA_NAME[$i]}: unsupported (no test discovery for this area; judge its tests from the diff)"
  elif [[ -s "$TMP/test.$i" ]]; then
    ANY=1
  fi
done
if [[ $ANY -eq 0 ]]; then
  echo "no tests changed"
  exit 0
fi

git -C "$WT" worktree add --detach "$OLD" "$BASE" >/dev/null 2>&1 || die "cannot create worktree at $BASE"

for i in "${!AREA_NAME[@]}"; do
  while IFS= read -r f; do
    mkdir -p "$OLD/$(dirname "$f")" && cp -p "$WT/$f" "$OLD/$f" || die "cannot copy $f"
  done < <(cat "$TMP/test.$i" "$TMP/support.$i")
done

RESULTS="$TMP/results.tsv"   # status<TAB>path<TAB>title<TAB>display
: > "$RESULTS"

# Results parsers (node, no dependencies). Argument: results file, area name, then the inputs.
parse_surefire() {
  node - "$@" <<'JS'
const fs = require('fs');
const [results, area, ...files] = process.argv.slice(2);
const decode = (v) => v
  .replace(/&#x([0-9a-fA-F]+);/g, (m, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (m, d) => String.fromCodePoint(Number(d)))
  .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const attr = (head, k) => {
  const m = head.match(new RegExp('\\s' + k + '="([^"]*)"'));
  return m ? decode(m[1]) : '';
};
let out = '';
for (const file of files) {
  const xml = fs.readFileSync(file, 'utf8');
  for (let part of xml.split(/<testcase\b/).slice(1)) {
    part = part.split('</testsuite>')[0];
    const head = part.slice(0, part.indexOf('>'));
    // match result elements only outside CDATA and system-out/system-err (a test may print "<failure>")
    const body = part.replace(/<!\[CDATA\[[\s\S]*?\]\]>/g, '').replace(/<system-(out|err)\b[\s\S]*?<\/system-\1>/g, '');
    if (/<skipped\b/.test(body)) continue;
    const bad = /<(failure|error)\b/.test(body);
    const classname = attr(head, 'classname');
    const name = attr(head, 'name');
    const cls = classname.split('$')[0].split('.').pop();
    out += [bad ? 'RED' : 'GREEN-ON-OLD', cls + '.java', name.split('(')[0], area + ' ' + classname + '.' + name].join('\t') + '\n';
  }
}
fs.appendFileSync(results, out);
JS
}

parse_vitest() {
  node - "$@" <<'JS'
const fs = require('fs');
const [results, area, dir, json, ...rels] = process.argv.slice(2);
const prefix = dir === '.' ? '' : dir + '/';
let out = '';
for (const suite of JSON.parse(fs.readFileSync(json, 'utf8')).testResults || []) {
  const name = suite.name || '?';
  const rel = rels.find((r) => name === r || name.endsWith('/' + r)) || name;
  const tests = suite.assertionResults || [];
  if (tests.length === 0) {
    if (suite.status === 'failed') out += ['RED-COMPILE', prefix + rel, '', area + ' ' + rel + ' (suite failed to load on old code)'].join('\t') + '\n';
    continue;
  }
  for (const t of tests) {
    if (['pending', 'skipped', 'todo'].includes(t.status)) continue;
    out += [t.status === 'failed' ? 'RED' : 'GREEN-ON-OLD', prefix + rel, t.title || '', area + ' ' + rel + ' > ' + (t.fullName || '?')].join('\t') + '\n';
  }
}
fs.appendFileSync(results, out);
JS
}

run_maven() {   # index
  local i="$1" dir="${AREA_DIR[$1]}" classes=() f
  while IFS= read -r f; do f="${f##*/}"; classes+=("${f%.java}"); done < "$TMP/test.$i"
  local list; list="$(IFS=,; echo "${classes[*]}")"
  local log="$TMP/maven.$i.log" mvn_cmd=(mvn)
  [[ -x "$OLD/$dir/mvnw" ]] && mvn_cmd=(./mvnw)
  ( cd "$OLD/$dir" && "${mvn_cmd[@]}" test "-Dtest=$list" -Dsurefire.failIfNoSpecifiedTests=false ) >"$log" 2>&1
  local rc=$?
  local reports=( "$OLD/$dir"/target/surefire-reports/TEST-*.xml )
  if [[ -e "${reports[0]}" ]]; then
    parse_surefire "$RESULTS" "${AREA_NAME[$i]}" "${reports[@]}" || return 2
    return 0
  fi
  if grep -q "COMPILATION ERROR" "$log"; then
    local c
    for c in "${classes[@]}"; do printf 'RED-COMPILE\t%s.java\t\t%s %s (old code does not compile)\n' "$c" "${AREA_NAME[$i]}" "$c" >> "$RESULTS"; done
    return 0
  fi
  echo "${AREA_NAME[$i]}: run produced no reports (exit $rc); tail of output:" >&2
  tail -n 30 "$log" >&2
  return 2
}

run_vitest() {   # index
  local i="$1" dir="${AREA_DIR[$1]}" rel=() f prefix=""
  [[ "$dir" == "." ]] || prefix="$dir/"
  while IFS= read -r f; do rel+=("${f#"$prefix"}"); done < "$TMP/test.$i"
  local log="$TMP/vitest.$i.log" json="$TMP/vitest.$i.json" install runner
  if [[ -f "$OLD/$dir/pnpm-lock.yaml" ]]; then
    install=(pnpm install --frozen-lockfile --prefer-offline); runner=(pnpm vitest)
  elif [[ -f "$OLD/$dir/package-lock.json" ]]; then
    install=(npm ci); runner=(npx vitest)
  else
    echo "SKIP ${AREA_NAME[$i]}: unsupported (no pnpm-lock.yaml or package-lock.json in $dir; judge its tests from the diff)"
    return 0
  fi
  ( cd "$OLD/$dir" && "${install[@]}" ) >"$log" 2>&1 || { echo "${AREA_NAME[$i]}: install failed; tail:" >&2; tail -n 30 "$log" >&2; return 2; }
  ( cd "$OLD/$dir" && "${runner[@]}" run "${rel[@]}" --reporter=json "--outputFile=$json" ) >>"$log" 2>&1
  if [[ ! -s "$json" ]]; then
    echo "${AREA_NAME[$i]}: vitest produced no JSON report; tail:" >&2; tail -n 30 "$log" >&2; return 2
  fi
  parse_vitest "$RESULTS" "${AREA_NAME[$i]}" "$dir" "$json" "${rel[@]}" || return 2
  return 0
}

STATUS=0
for i in "${!AREA_NAME[@]}"; do
  [[ -s "$TMP/test.$i" ]] || continue
  case "${AREA_KIND[$i]}" in
    maven) run_maven "$i" || STATUS=2 ;;
    vitest) run_vitest "$i" || STATUS=2 ;;
  esac
done
[[ $STATUS -eq 2 ]] && die "could not run the tests on the old code (not a pass)"

cat "$TMP"/test.* > "$TMP/testfiles"
echo "red-green-check: base=$BASE"
# A GREEN test only counts as GREEN-ON-OLD when the child touched it (changed lines per file from git; every
# line of an untracked or new file); untouched tests in a changed file show as UNCHANGED.
node - "$WT" "$BASE" "$RESULTS" "$TMP/testfiles" <<'JS'
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const [wt, base, results, testfiles] = process.argv.slice(2);
const git = (...args) => spawnSync('git', ['-C', wt, ...args], { encoding: 'utf8' });
const touched = new Map();
for (const f of fs.readFileSync(testfiles, 'utf8').split('\n').filter(Boolean)) {
  const lines = new Set();
  if (git('ls-files', '--error-unmatch', '--', f).status === 0 && git('cat-file', '-e', base + ':' + f).status === 0) {
    for (const l of git('diff', '-U0', base, '--', f).stdout.split('\n')) {
      const m = l.match(/^@@ -\S+ \+(\d+)(?:,(\d+))? @@/);
      if (!m) continue;
      const a = Number(m[1]);
      const n = m[2] === undefined ? 1 : Number(m[2]);
      for (let i = a; i < a + n; i++) lines.add(i);
    }
  } else {
    const count = fs.readFileSync(path.join(wt, f), 'utf8').split('\n').length;
    for (let i = 1; i <= count; i++) lines.add(i);
  }
  touched.set(f, lines);
}
const starts = /^\s*(@Test|@ParameterizedTest|@RepeatedTest|it\(|it\.each|test\(|it\.skip|test\.each)/;
function segmentTouched(file, title) {
  const key = [...touched.keys()].find((k) => k === file || k.endsWith('/' + file));
  if (!title || key === undefined) return true;
  let lines;
  try { lines = fs.readFileSync(path.join(wt, key), 'utf8').split('\n'); } catch (e) { return true; }
  const idx = [];
  lines.forEach((l, i) => { if (starts.test(l)) idx.push(i + 1); });
  idx.push(lines.length + 1);
  for (let k = 0; k + 1 < idx.length; k++) {
    const a = idx[k];
    const b = idx[k + 1];
    if (lines.slice(a - 1, b - 1).some((l) => l.includes(title))) {
      return [...touched.get(key)].some((n) => n >= a && n < b);
    }
  }
  return true;   // title not found: stay conservative
}
const rows = [];
let green = 0;
for (const l of fs.readFileSync(results, 'utf8').split('\n').filter(Boolean)) {
  const [status, file, title, disp] = l.split('\t');
  let st = status;
  if (st === 'GREEN-ON-OLD') {
    if (!segmentTouched(file, title)) st = 'UNCHANGED';
    else green++;
  }
  rows.push([st, disp]);
}
const order = { 'GREEN-ON-OLD': 0, 'RED-COMPILE': 1, 'RED': 2, 'UNCHANGED': 3 };
rows.sort((x, y) => order[x[0]] - order[y[0]] || (x[1] < y[1] ? -1 : x[1] > y[1] ? 1 : 0));
for (const [st, disp] of rows) console.log(st.padEnd(13) + ' ' + disp);
console.log('RESULT: ' + (green ? 'GREEN-ON-OLD tests found (suspicious)' : 'all changed tests are red on old code'));
process.exit(green ? 1 : 0);
JS
exit $?
